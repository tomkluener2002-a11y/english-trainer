import type { Cefr, Choice, PlacementQuestion } from '../schema'

/**
 * Fragenbank für den adaptiven Einstufungstest: 15 Fragen je Niveau A1–C1.
 * Pro Niveau: 6 fill, 3 choice, 2 listen-choice, 2 translate, 2 type.
 */

/** Baut die Optionen: `right` an Position `pos`, die übrigen (falschen) in Reihenfolge. */
function opts(right: string, wrong: string[], pos: number): Choice[] {
  const list: Choice[] = wrong.map((text) => ({ text }))
  list.splice(pos, 0, { text: right, correct: true })
  return list
}

const fill = (id: string, cefr: Cefr, sentence: string, right: string, wrong: string[], pos: number, explanation: string): PlacementQuestion => ({
  id,
  cefr,
  exercise: { id: 'q', type: 'fill', sentence, choices: opts(right, wrong, pos), explanation },
})

const choice = (
  id: string,
  cefr: Cefr,
  prompt: string,
  question: string,
  right: string,
  wrong: string[],
  pos: number,
  explanation: string,
  questionLang: 'en' | 'de' = 'en',
): PlacementQuestion => ({
  id,
  cefr,
  exercise: { id: 'q', type: 'choice', prompt, question, questionLang, choices: opts(right, wrong, pos), explanation },
})

const listen = (id: string, cefr: Cefr, audio: string, prompt: string, right: string, wrong: string[], pos: number, explanation: string): PlacementQuestion => ({
  id,
  cefr,
  exercise: { id: 'q', type: 'listen-choice', audio, prompt, choices: opts(right, wrong, pos), explanation },
})

const translate = (
  id: string,
  cefr: Cefr,
  prompt: string,
  answer: string,
  distractors: string[],
  explanation: string,
  accepted?: string[],
): PlacementQuestion => ({
  id,
  cefr,
  exercise: { id: 'q', type: 'translate', direction: 'de-en', prompt, answer, distractors, explanation, ...(accepted ? { accepted } : {}) },
})

const type = (id: string, cefr: Cefr, sentence: string, accepted: string[], hint: string, explanation: string): PlacementQuestion => ({
  id,
  cefr,
  exercise: { id: 'q', type: 'type', sentence, accepted, hint, explanation },
})

